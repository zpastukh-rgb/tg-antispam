def root_matches_token(ww: str, t: str) -> bool:
    """
    Совпадение одного корня с одним токеном (оба уже lower + ё→е).
    Не используется для фраз с пробелом и для корней длины ≤2 (их обрабатывает вызывающий код).
    """
    if not ww or not t:
        return False
    if t in SAFE_FULL_TOKENS:
        return False

    if ww == "бля":
        if t == "бля":
            return True
        if t.startswith("блях") or t.startswith("бляш"):
            return False
        if t.startswith("бля"):
            return True
        return False

    # Букмекерские бренды / термины: префикс ловит «париматч», но не «париж» / «паритет» / «парик».
    if ww == "пари":
        if t == "пари":
            return True
        if any(t.startswith(p) for p in _PARI_NON_BETTING_PREFIXES):
            return False
        if t.startswith("пари"):
            return True
        return ww in t

    if ww == "леон":
        if t == "леон":
            return True
        if t.startswith(("леонид", "леонард", "леонтьев", "леонье", "леонька", "леончик")):
            return False
        if t.startswith("леон"):
            return True
        return ww in t

    # «Тотальный» / «тотальность» — не ставка; «тотал», «тотала» (жарг.) — оставляем.
    if ww == "тотал":
        if t == "тотал":
            return True
        if t.startswith("тоталь"):
            return False
        if t.startswith("тотал"):
            return True
        return ww in t

    if ww in ROOTS_PREFIX_ONLY:
        if t == ww:
            return True
        if t.startswith(ww):
            return True
        if ww in ("bet", "бет"):
            if _bet_prefix_blocked(t, ww):
                return False
            if t.endswith(ww) and len(t) > len(ww):
                # «альфабет», «alphabet» — не ставки.
                if ww == "бет" and t.endswith("абет"):
                    return False
                if ww == "bet" and t.endswith("abet"):
                    return False
                return True
        return False

    return t == ww or t.startswith(ww) or ww in t
